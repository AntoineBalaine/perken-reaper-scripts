-- @noindex
-- Generates src/tones.zig from the design lab's ui-lab/tones.lua, so that the plugin's panel lists the
-- same tones as the lab does. The lab's file is itself generated from the roland-vr09 project.
--
--   lua tools/gen_zig_tones.lua ui-lab/tones.lua > src/tones.zig

local tones = assert(loadfile(arg[1] or "ui-lab/tones.lua"))()

-- A Lua string as a Zig string literal.
local function zig_string(text)
  return '"' .. text:gsub('[\\"]', "\\%0") .. '"'
end

local out = {}
local function emit(text) out[#out + 1] = text end

emit("//! The keyboard's tones, generated by tools/gen_zig_tones.lua from the design lab's ui-lab/tones.lua.")
emit("//! Do not edit by hand.")
emit("")
emit("/// A tone of the keyboard, with the three bytes that select it.")
emit("pub const Tone = struct {")
emit("    name: [:0]const u8,")
emit("    group: [:0]const u8,")
emit("    number: u8,")
emit("    msb: u8,")
emit("    lsb: u8,")
emit("    program: u8,")
emit("};")
emit("")
for _, list in ipairs({ "piano", "synth", "drum" }) do
  emit(("pub const %s = [_]Tone{"):format(list))
  for _, tone in ipairs(tones[list]) do
    emit(("    .{ .name = %s, .group = %s, .number = %d, .msb = %d, .lsb = %d, .program = %d },"):format(
      zig_string(tone.name), zig_string(tone.group), tone.number, tone.msb, tone.lsb, tone.program))
  end
  emit("};")
  emit("")
end
print(table.concat(out, "\n"))
