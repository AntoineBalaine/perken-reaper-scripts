-- Generates src/extras.zig from the design lab's ui-lab/extras.lua, so that the plugin's panel draws the
-- same documented parameters as the lab does, and the lab stays the place where they are edited.
--
--   lua tools/gen_zig_extras.lua ui-lab/extras.lua > src/extras.zig

local path = arg[1] or "ui-lab/extras.lua"
local chunk = assert(loadfile(path))
local extras = chunk()

-- A Lua string as a Zig string literal.
local function zig_string(text)
  return '"' .. text:gsub('[\\"]', "\\%0"):gsub("\n", "\\n") .. '"'
end

-- The reasons are written once, as constants, because many parameters share one.
local reasons, reason_names = {}, {}
local function reason_of(param)
  local text = param.disabled
  if not text then return nil end
  if not reasons[text] then
    reason_names[#reason_names + 1] = text
    reasons[text] = "reason_" .. #reason_names
  end
  return reasons[text]
end

local lines = {}
local function emit(text) lines[#lines + 1] = text end

local entries = {}
for _, param in ipairs(extras) do
  local fields = { (".id = %s"):format(zig_string(param.id)), (".label = %s"):format(zig_string(param.label)) }
  if param.short then fields[#fields + 1] = (".short = %s"):format(zig_string(param.short)) end
  fields[#fields + 1] = (".low = %d"):format(param.low)
  fields[#fields + 1] = (".high = %d"):format(param.high)
  if param.shift then fields[#fields + 1] = (".shift = %d"):format(param.shift) end
  if param.scale then fields[#fields + 1] = (".scale = %d"):format(param.scale) end
  if param.signed then fields[#fields + 1] = ".signed = true" end
  if param.unit then fields[#fields + 1] = (".unit = %s"):format(zig_string(param.unit)) end
  if param.default then fields[#fields + 1] = (".default = %d"):format(param.default) end
  -- A parameter is disabled only when the lab gives a reason: the others are mock-ups that the panel lets the
  -- user move, and nothing is sent to the keyboard.
  local reason = reason_of(param)
  if reason then fields[#fields + 1] = (".disabled = %s"):format(reason) end
  if param.names then
    local names = {}
    for _, name in ipairs(param.names) do names[#names + 1] = zig_string(name) end
    fields[#fields + 1] = (".names = &.{ %s }"):format(table.concat(names, ", "))
  end
  if param.values then
    local values = {}
    for _, value in ipairs(param.values) do values[#values + 1] = tostring(value) end
    fields[#fields + 1] = (".values = &.{ %s }"):format(table.concat(values, ", "))
  end
  entries[#entries + 1] = "    .{ " .. table.concat(fields, ", ") .. " },"
end

emit("//! The parameters that Roland documents for the VR-09 and that the plugin's catalog does not have yet,")
emit("//! generated by tools/gen_zig_extras.lua from the design lab's ui-lab/extras.lua. Do not edit by hand.")
emit("//!")
emit("//! The panel draws them as the lab does: a control with a reason is disabled, with the reason in a tooltip, and")
emit("//! the others can be moved on the screen. Nothing here is sent to a keyboard.")
emit("")
emit("/// A documented parameter that the plugin does not have.")
emit("pub const Extra = struct {")
emit("    id: []const u8,")
emit("    label: []const u8,")
emit("    /// The shorter name that a knob shows under itself, when it has one.")
emit("    short: []const u8 = \"\",")
emit("    low: i32,")
emit("    high: i32,")
emit("    shift: i32 = 0,")
emit("    scale: i32 = 1,")
emit("    signed: bool = false,")
emit("    unit: []const u8 = \"\",")
emit("    default: ?i32 = null,")
emit("    /// Why the control cannot be used, or null when the panel lets the user move it.")
emit("    disabled: ?[:0]const u8 = null,")
emit("    names: []const []const u8 = &.{},")
emit("    values: []const i32 = &.{},")
emit("};")
emit("")
for i, text in ipairs(reason_names) do
  emit(("const reason_%d: [:0]const u8 = %s;"):format(i, zig_string(text)))
end
emit("")
emit("pub const params = [_]Extra{")
for _, entry in ipairs(entries) do emit(entry) end
emit("};")
emit("")
emit("/// The extra with this id, or null.")
emit("pub fn find(id: []const u8) ?*const Extra {")
emit("    for (&params) |*extra| {")
emit("        if (@import(\"std\").mem.eql(u8, extra.id, id)) return extra;")
emit("    }")
emit("    return null;")
emit("}")
print(table.concat(lines, "\n"))
