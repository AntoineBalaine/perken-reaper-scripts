#!/usr/bin/env python3
"""Generates src/catalog.zig from the Touché remap catalog of the roland-vr09 project.

  tools/gen_catalog.py /path/to/roland-vr09/web/public/maps/targets.json > src/catalog.zig

The effects (reverb, MFX, delay) are not in that catalog. tools/effects.json, next to this script,
lists them in the same shape, with an optional "names" list that the panel shows in place of the
number, and the generator appends them.

Because the parameters the plugin exposes come from addresses that were written and read back on a
real unit, the catalog keeps only the entries whose status is "verified" (DT1 writes) or
"documented" (Control Change messages). The entries marked "unavailable" are refused by the unit.
"""
import json
import os
import sys

# The group of a parameter, chosen from the start of its id, in the order of the checks.
GROUPS = [
    ("organ-upper-", "Organ upper drawbars"),
    ("organ-lower-", "Organ lower drawbars"),
    ("organ-", "Organ"),
    ("overdrive", "Organ"),
    ("leakage", "Organ"),
    ("click-", "Organ"),
    ("rotary-", "Rotary"),
    ("woofer-", "Rotary"),
    ("tweeter-", "Rotary"),
    ("reverb-", "Effects"),
    ("vibrato-", "Effects"),
    ("mfx-", "Effects"),
    ("delay-", "Effects"),
    ("compressor-", "Effects"),
    ("rhythm-", "Mixer"),
    ("song-", "Mixer"),
    ("upper-piano-volume", "Mixer"),
    ("upper-synth-volume", "Mixer"),
    ("upper-synth2-volume", "Mixer"),
    ("lower-piano-volume", "Mixer"),
    ("lower-synth-volume", "Mixer"),
    ("upper-synth-", "Synth upper"),
    ("lower-synth-", "Synth lower"),
    ("cc-upper-", "Control change upper"),
    ("cc-lower-", "Control change lower"),
    ("cc-piano-", "Control change piano"),
    ("cc-master-", "Control change master"),
]


def group_of(identifier):
    for prefix, group in GROUPS:
        if identifier.startswith(prefix):
            return group
    sys.exit(f"no group for {identifier}")


def pack(address):
    value = 0
    for byte in address:
        value = (value << 7) | byte
    return value


def zig_string(text):
    return json.dumps(text, ensure_ascii=False)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    targets = json.load(open(sys.argv[1]))
    effects = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "effects.json")))
    kept = [t for t in targets + effects if t["status"] in ("verified", "documented")]
    out = []
    out.append("//! The parameters the plugin exposes, generated by tools/gen_catalog.py from the")
    out.append("//! Touché remap catalog of the roland-vr09 project. Do not edit by hand.")
    out.append("")
    out.append("pub const Kind = enum { dt1, cc };")
    out.append("")
    out.append("pub const Param = struct {")
    out.append("    id: []const u8,")
    out.append("    label: []const u8,")
    out.append("    group: []const u8,")
    out.append("    kind: Kind,")
    out.append("    /// The packed three-byte address of a DT1 parameter, zero for a CC.")
    out.append("    address: u32,")
    out.append("    low: u8,")
    out.append("    high: u8,")
    out.append("    /// The MIDI channel (1 to 16) and controller number of a CC, zero for a DT1.")
    out.append("    channel: u8,")
    out.append("    cc: u8,")
    out.append("    /// What the panel shows for each value from `low`, instead of the number.")
    out.append("    names: []const []const u8 = &.{},")
    out.append("};")
    out.append("")
    out.append("pub const params = [_]Param{")
    for t in kept:
        kind = t["kind"]
        address = pack(t["address"]) if kind == "dt1" else 0
        channel = t.get("channel", 0) if kind == "cc" else 0
        cc = t.get("cc", 0) if kind == "cc" else 0
        # The label of a CC entry repeats its controller number, which the group already shows.
        names = ""
        if t.get("names"):
            names = ", .names = &.{ %s }" % ", ".join(zig_string(n) for n in t["names"])
        out.append(
            "    .{ .id = %s, .label = %s, .group = %s, .kind = .%s, .address = %d, .low = %d, .high = %d, .channel = %d, .cc = %d%s },"
            % (zig_string(t["id"]), zig_string(t["label"]), zig_string(group_of(t["id"])), kind, address, t["low"], t["high"], channel, cc, names)
        )
    out.append("};")
    print("\n".join(out))


main()
